using System.Globalization;
using System.Text;

namespace Diffra.LineCounts.Oracle;

/// <summary>
/// Renders <c>docs/line-counts-conformance.md</c> from the frozen oracle and the rulings: per case,
/// what each tool counted, the majority and Diffra's ruling. The harness writes it; <c>verify</c>
/// fails when it is out of date.
/// </summary>
internal static class ConformanceTable
{
    public static string Render(Oracle oracle, SortedDictionary<string, Ruling> rulings)
    {
        var text = new StringBuilder();
        text.Append("# Line-count conformance\n\n");
        text.Append("<!-- Generated by tests/LineCounts.Oracle (`table`) from tests/line-counts/oracle.json and\n");
        text.Append("     tests/line-counts/rulings.json. Do not edit by hand. -->\n\n");
        text.Append("This table is the evidence behind [decision record 0010](adr/0010-line-counts.md). Each case\n");
        text.Append("in `tests/line-counts/corpus` isolates one edge case. Each cell gives code/comments/blanks\n");
        text.Append("as the tool counted the file, and `—` where the tool did not count it. The majority is the\n");
        text.Append("triple at least two tools give exactly. The ruling is what Diffra's counter must give: the\n");
        text.Append("majority, a deliberate divergence with its reason, or a question still open for the owner.\n\n");
        text.Append("Tools: ");
        text.Append(string.Join(", ", Tools.All.Select(t => $"{t.Name} {oracle.Versions[t.Name]}")));
        text.Append(".\n\n");

        var all = oracle.Cases.Count(c => Distinct(c) == 1);
        var two = oracle.Cases.Count(c => Distinct(c) == 2);
        var split = oracle.Cases.Count(c => Distinct(c) == 3);
        text.Append(CultureInfo.InvariantCulture, $"Of {oracle.Cases.Count} cases, all three tools agree on {all}, two agree on {two}, and the three split on {split}. ");
        var counts = rulings.Values.GroupBy(r => r.Kind).ToDictionary(g => g.Key, g => g.Count(), StringComparer.Ordinal);
        text.Append(CultureInfo.InvariantCulture, $"Rulings: {counts.GetValueOrDefault("majority")} majority, {counts.GetValueOrDefault("diverge")} diverge, {counts.GetValueOrDefault("open")} open.\n\n");

        text.Append("Agreement between each pair of tools, over the cases both count:\n\n");
        text.Append("| Pair | Same triple | Same code | Same comments | Same blanks |\n");
        text.Append("| --- | --- | --- | --- | --- |\n");
        for (var i = 0; i < Tools.All.Count; i++)
        {
            for (var j = i + 1; j < Tools.All.Count; j++)
            {
                var a = Tools.All[i].Name;
                var b = Tools.All[j].Name;
                var both = oracle.Cases.Select(c => (A: c.Results[a], B: c.Results[b])).Where(p => p.A.Counted && p.B.Counted).ToList();
                text.Append(CultureInfo.InvariantCulture, $"| {a} and {b} | {Share(both.Count(p => p.A.Counts == p.B.Counts), both.Count)} | {Share(both.Count(p => p.A.Code == p.B.Code), both.Count)} | {Share(both.Count(p => p.A.Comments == p.B.Comments), both.Count)} | {Share(both.Count(p => p.A.Blanks == p.B.Blanks), both.Count)} |\n");
            }
        }

        foreach (var group in oracle.Cases.OrderBy(c => c.Path, StringComparer.Ordinal).GroupBy(c => c.Path.Split('/')[0]))
        {
            text.Append(CultureInfo.InvariantCulture, $"\n## {group.Key}\n\n");
            text.Append("| Case | Isolates | Lines | ");
            text.Append(string.Join(" | ", Tools.All.Select(t => t.Name)));
            text.Append(" | Majority | Ruling |\n");
            text.Append("| --- | --- | --- | ");
            text.Append(string.Join(" | ", Tools.All.Select(_ => "---")));
            text.Append(" | --- | --- |\n");
            foreach (var result in group)
            {
                var ruling = rulings.GetValueOrDefault(result.Path);
                text.Append(CultureInfo.InvariantCulture, $"| `{result.Path[(group.Key.Length + 1)..]}` | {Escape(ruling?.Isolates ?? string.Empty)} | {result.Lines} | ");
                text.Append(string.Join(" | ", Tools.All.Select(t => Cell(result.Results[t.Name]))));
                var majority = result.Majority()?.ToString() ?? (result.MajorityNotCounted ? "—" : "split");
                text.Append(CultureInfo.InvariantCulture, $" | {majority} | {RulingCell(ruling)} |\n");
            }
        }

        return text.ToString();
    }

    private static int Distinct(CaseResult result) => result.Results.Values.Select(r => r.Counts?.ToString() ?? "—").Distinct(StringComparer.Ordinal).Count();

    private static string Share(int part, int whole) =>
        string.Create(CultureInfo.InvariantCulture, $"{part} of {whole}");

    private static string Cell(ToolResult result) => result.Counted ? result.Counts!.ToString() : "—";

    private static string RulingCell(Ruling? ruling) => ruling?.Kind switch
    {
        null => "none",
        "majority" => "majority",
        "diverge" => $"diverge: {ruling.Expected}. {Escape(ruling.Reason ?? string.Empty)}",
        "open" => $"open: {Escape(ruling.Reason ?? string.Empty)}",
        _ => Escape(ruling.Kind),
    };

    private static string Escape(string text) => text.Replace("|", "\\|", StringComparison.Ordinal);
}
